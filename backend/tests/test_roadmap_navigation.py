"""
Navigation additions: adding a job's missing skill to the learning roadmap
(no duplicates, survives re-analysis and regeneration), roadmap groups linking
to the skill's quiz, match breakdowns knowing what is already planned, and
career recommendations linking to the matching Jobs-page domain.
"""
from tests.base import app, db, reset_db, make_student, login  # must be first

import json
import unittest
from datetime import datetime, timezone
from unittest import mock

from models import JobListing, Organisation, Skill, SkillGap, SkillVerification, StudyPlan


def _job(**over):
    now = datetime.now(timezone.utc).replace(tzinfo=None)
    data = dict(external_id=f"t:{over.get('title', 'x')}", title='Data Engineer', company='Acme',
                description='Build pipelines with Python, SQL and Kafka.', location='Pune', status='active',
                source='Test', source_provider='test', is_sample=False, collected_at=now, first_seen_at=now,
                required_skills=json.dumps(['python', 'sql', 'kafka']), preferred_skills=json.dumps(['airflow']),
                career_category='Data Engineering')
    data.update(over)
    return JobListing(**data)


class RoadmapFromJobTests(unittest.TestCase):
    def setUp(self):
        # Roadmap templates would otherwise be generated by Gemini: stay offline, use the fallback
        # and job-match resource lookups (YouTube / GitHub) are not called
        for target in ('utils.roadmap_generator.generate_roadmap_days', 'utils.youtube_api.search_youtube_videos',
                       'utils.github_api.search_github_projects'):
            patcher = mock.patch(target, return_value=[])   # [] = "nothing generated / found"
            patcher.start()
            self.addCleanup(patcher.stop)
        reset_db()
        # a career with built-in requirements, so the skill-gap analysis needs no AI call
        self.sid = make_student('road@test.com', target_career='Data Scientist')
        with app.app_context():
            py = Skill(student_id=self.sid, skill_name='python', source='resume', evidence_strength='applied')
            sql = Skill(student_id=self.sid, skill_name='sql', source='resume', evidence_strength='listed_only')
            db.session.add_all([py, sql])
            db.session.flush()
            db.session.add(SkillVerification(student_id=self.sid, skill_id=py.id, quiz_question_count=5,
                                             quiz_correct_count=5, quiz_score_percent=100.0, verification_score=0.9))
            job = _job()
            org = Organisation(name='Draft Co', verification_status='verified')
            db.session.add(org)
            db.session.flush()
            draft = _job(title='Secret draft', external_id='t:draft', status='draft', organisation_id=org.id)
            db.session.add_all([job, draft])
            db.session.commit()
            self.job_id, self.draft_id, self.sql_id = job.id, draft.id, sql.id
        self.c = app.test_client()
        login(self.c, 'road@test.com')

    def add(self, skill, job_id=None, **extra):
        res = self.c.post('/api/student/roadmap/skills', json={'skill_name': skill, 'job_id': job_id, **extra})
        return res.status_code, res.get_json()

    def plan_names(self):
        with app.app_context():
            return sorted({p.skill_name for p in StudyPlan.query.filter_by(student_id=self.sid).all()})

    def test_add_missing_job_skill_once(self):
        code, body = self.add('Kafka', self.job_id)
        self.assertEqual(code, 201, body)
        self.assertTrue(body['added'])
        self.assertTrue(body['roadmap_group']['from_job'])
        self.assertEqual(body['roadmap_group']['category'], 'From job: Data Engineer')
        self.assertEqual(body['roadmap_group']['importance'], 'High')       # required for this job
        self.assertGreater(len(body['roadmap_group']['days']), 0)
        days = len(body['roadmap_group']['days'])

        for variant in ('kafka', ' KAFKA ', 'Kafka'):
            code, body = self.add(variant, self.job_id)
            self.assertEqual(code, 200, body)
            self.assertFalse(body['added'])
            self.assertIn('already on your learning roadmap', body['message'])
        with app.app_context():
            self.assertEqual(SkillGap.query.filter_by(student_id=self.sid).count(), 1)
            self.assertEqual(StudyPlan.query.filter_by(student_id=self.sid).count(), days)

        code, body = self.add('airflow', self.job_id)
        self.assertEqual(code, 201)
        self.assertEqual(body['roadmap_group']['importance'], 'Medium')     # preferred for this job

    def test_verified_and_invalid_skills_are_not_added(self):
        code, body = self.add('Python', self.job_id)
        self.assertEqual(code, 200)
        self.assertFalse(body['added'])
        self.assertTrue(body['verified'])
        self.assertEqual(self.add('rust', self.job_id)[0], 400)            # not a skill of this job
        self.assertEqual(self.add('kafka', self.draft_id)[0], 404)         # hidden employer draft
        self.assertEqual(self.add('', None)[0], 400)
        self.assertEqual(self.add('x' * 61, None)[0], 400)
        self.assertEqual(self.plan_names(), [])

    def test_skill_added_without_a_job_is_labelled_and_kept(self):
        code, body = self.add('statistics')
        self.assertEqual(code, 201, body)
        self.assertEqual(body['roadmap_group']['category'], 'Added by you')
        self.assertFalse(body['roadmap_group']['from_job'])
        self.c.post('/api/student/analyze_skill_gap')
        with app.app_context():
            names = [g.missing_skill.lower() for g in SkillGap.query.filter_by(student_id=self.sid).all()]
        self.assertEqual(names.count('statistics'), 1)

    def test_existing_roadmap_skill_is_a_duplicate(self):
        with app.app_context():
            db.session.add(SkillGap(student_id=self.sid, missing_skill='Kafka', importance='High', category='Required'))
            db.session.commit()
        code, body = self.add('kafka', self.job_id)
        self.assertEqual((code, body['added']), (200, False))

    def test_job_skills_survive_reanalysis_and_regeneration(self):
        self.add('kafka', self.job_id)
        res = self.c.post('/api/student/analyze_skill_gap')
        self.assertEqual(res.status_code, 200, res.get_json())
        with app.app_context():
            gaps = SkillGap.query.filter_by(student_id=self.sid).all()
            kafka = [g for g in gaps if g.missing_skill.lower() == 'kafka']
            self.assertEqual(len(kafka), 1, [g.missing_skill for g in gaps])   # still there, never twice
            keys = [g.missing_skill.lower() for g in gaps]
            self.assertEqual(len(keys), len(set(keys)))
        res = self.c.post('/api/student/generate_roadmap')
        self.assertEqual(res.status_code, 200)
        self.assertIn('kafka', [g['skill'].lower() for g in res.get_json()['roadmap']])

    def test_roadmap_group_links_and_match_breakdown(self):
        with app.app_context():
            db.session.add(SkillGap(student_id=self.sid, missing_skill='sql', importance='High', category='Required'))
            db.session.commit()
        self.c.post('/api/student/generate_roadmap')
        res = self.c.get('/api/student/get_roadmap').get_json()
        sql = next(g for g in res['roadmap'] if g['skill'].lower() == 'sql')
        self.assertEqual(sql['skill_id'], self.sql_id)                      # quiz link target
        self.assertFalse(sql['verified'])
        self.assertFalse(sql['from_job'])

        self.add('kafka', self.job_id)
        res = self.c.get(f'/api/student/jobs/{self.job_id}/match')
        self.assertEqual(res.status_code, 200)
        self.assertIn('kafka', res.get_json()['roadmap_skills'])


class CareerJobsLinkTests(unittest.TestCase):
    def setUp(self):
        reset_db()
        make_student('career@test.com')
        self.c = app.test_client()
        login(self.c, 'career@test.com')

    def test_recommendations_carry_jobs_domain(self):
        body = self.c.get('/api/student/career_recommendations').get_json()
        self.assertTrue(body['recommendations'])
        domains = {r.get('career_key') or r['career']: r['job_domain'] for r in body['recommendations']}
        self.assertTrue(all('job_domain' in r for r in body['recommendations']))
        by_lower = {k.lower(): v for k, v in domains.items()}
        self.assertEqual(by_lower.get('data scientist'), 'Data Science')
        self.assertEqual(by_lower.get('devops engineer'), 'Cloud & DevOps')


if __name__ == '__main__':
    unittest.main()
