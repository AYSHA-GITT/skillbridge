"""
Curated, reviewed multiple-choice questions for skill verification quizzes.

Why this file exists: the question bank used to depend entirely on Gemini
(free tier, 20 requests/day). When the quota ran out, 23 of the 28 skills that
careers require had zero questions and could not be verified at all, and no
skill had a single Hard question. These questions were written and checked by
hand; they are inserted into the question_bank table only when missing
(`flask --app app skills seed-questions`, and automatically the first time a
quiz for the skill is requested), so AI-generated questions still top the bank
up to MINIMUM_QUESTIONS_PER_SKILL when a provider is available.

Conventions
- skill_name is the canonical lower-case taxonomy name (utils/skill_taxonomy.py).
- Every career-required skill has 6 questions: 2 Easy, 2 Medium, 2 Hard.
  Common nice-to-have skills have 5 (2/2/1).
- The correct option is placed deterministically from a hash of the question so
  the raw bank has no positional bias (the API additionally shuffles options per
  student).
- No "all/none of the above" options; every option is distinct and plausible.
"""
import hashlib


def _q(skill, difficulty, question, correct, *wrong):
    if len(wrong) != 3:
        raise ValueError(f"need exactly 3 wrong options for: {question}")
    options = [correct, *wrong]
    pos = int(hashlib.sha256(question.encode("utf-8")).hexdigest(), 16) % 4
    options.insert(pos, options.pop(0))
    return {
        "skill_name": skill, "difficulty": difficulty, "question": question,
        "option_a": options[0], "option_b": options[1], "option_c": options[2], "option_d": options[3],
        "correct_answer": "ABCD"[pos],
    }


